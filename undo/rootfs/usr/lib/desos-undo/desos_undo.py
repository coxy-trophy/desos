def read_json(path, default=None):
    try:
        return json.loads(Path(path).read_text())
    except (OSError, ValueError):
        return default


def write_json(path, value, mode=0o644):
    write_text(path, json.dumps(value, indent=1, sort_keys=True) + '\n', mode)


def write_text(path, text, mode=0o644):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + '.tmp')
    with open(temporary, 'w') as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())
    os.chmod(temporary, mode)
    os.replace(temporary, path)


@contextlib.contextmanager
def locked(host):
    directory = host.path(STATE)
    directory.mkdir(parents=True, exist_ok=True)
    with contextlib.suppress(OSError):
        os.chmod(directory, 0o755)
    with open(directory / 'lock', 'w') as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        yield


def stamp(host):
    return time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(host.now()))


def read_env(path):
    try:
        text = Path(path).read_bytes().decode('ascii', 'replace')
    except OSError:
        return {}
    values = {}
    for line in text.split('\n'):
        if line and not line.startswith('#') and '=' in line:
            key, value = line.split('=', 1)
            values[key] = value
    return values


def write_env(path, values):
    """Rewrite a GRUB environment block in place (GRUB writes it by block
    list, so the file keeps its fixed 1024-byte size and is never replaced)."""
    body = ENV_HEADER + ''.join('%s=%s\n' % (key, values[key]) for key in sorted(values) if values[key] != '')
    data = body.encode('ascii')
    if len(data) > ENV_SIZE:
        raise UndoError('GRUB environment block overflow', 'env-overflow')
    data += b'#' * (ENV_SIZE - len(data))
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT, 0o644)
    try:
        os.write(descriptor, data)
        os.ftruncate(descriptor, ENV_SIZE)
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def boot_arming(host):
    """How the generated grub.cfg of this root counts boots. The marker is read
    from grub.cfg itself so tool and boot loader can never disagree."""
    try:
        match = MARKER.search(host.path(GRUB_CFG).read_text(errors='replace'))
    except OSError:
        match = None
    if not match:
        return {'mode': 'unarmed', 'env': None, 'threshold': None}
    return {'mode': match.group(1), 'env': match.group(2), 'threshold': int(match.group(3))}


def update_env(host, arming, **changes):
    if not arming['env']:
        return {}
    path = host.path(arming['env'])
    values = {key: value for key, value in read_env(path).items() if key in ENV_KEYS}
    values.update({key: str(value) for key, value in changes.items()})
    write_env(path, values)
    return values


def add_notice(host, kind, message, **extra):
    path = host.path(STATE + '/notices.json')
    notices = read_json(path, [])
    notice = {'id': max([item['id'] for item in notices], default=0) + 1, 'time': stamp(host),
              'kind': kind, 'message': message, 'acknowledged': False}
    notice.update(extra)
    write_json(path, (notices + [notice])[-50:])
    return notice


