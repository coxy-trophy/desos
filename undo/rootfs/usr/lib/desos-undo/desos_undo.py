def snapshot_dir(host, identifier):
    return host.path('%s/%d' % (SNAPSHOTS, identifier))


def snapshot_tree(host, identifier):
    return snapshot_dir(host, identifier) / 'snapshot'


def list_snapshots(host):
    found = []
    try:
        names = os.listdir(host.path(SNAPSHOTS))
    except OSError:
        return found
    for name in names:
        if not name.isdigit() or not (host.path(SNAPSHOTS) / name / 'snapshot').is_dir():
            continue
        info = read_json(host.path(SNAPSHOTS) / name / 'info.json')
        if not isinstance(info, dict):
            info = {'schema': SCHEMA, 'kind': 'unknown', 'reason': 'metadata missing', 'created': None}
        info['id'] = int(name)
        found.append(info)
    return sorted(found, key=lambda info: info['id'])


def get_snapshot(host, identifier):
    for info in list_snapshots(host):
        if info['id'] == identifier:
            return info
    raise UndoError('Snapshot %d does not exist.' % identifier, 'no-such-snapshot')


def next_id(host):
    counter = host.path(STATE + '/next-id')
    try:
        stored = int(counter.read_text())
    except (OSError, ValueError):
        stored = 1
    existing = [int(name) for name in os.listdir(host.path(SNAPSHOTS)) if name.isdigit()]
    identifier = max([stored] + [value + 1 for value in existing])
    write_text(counter, '%d\n' % (identifier + 1))
    return identifier


def boot_kernels(tree):
    boot = Path(tree) / 'boot'
    versions = [path.name[len('vmlinuz-'):] for path in boot.glob('vmlinuz-*')
                if (boot / ('initrd.img-' + path.name[len('vmlinuz-'):])).exists()]
    return sorted(versions, key=version_key)


def preferred_kernel(info):
    kernels = (info.get('boot') or {}).get('kernels') or []
    if info.get('kernel') in kernels:
        return info['kernel']
    desos = [version for version in kernels if version.endswith('-desos')]
    return (desos or kernels or [None])[-1]


def create_snapshot(host, cfg, kind, reason, source=None, **extra):
    identifier = next_id(host)
    directory = snapshot_dir(host, identifier)
    directory.mkdir(parents=True)
    os.chmod(directory, 0o755)
    try:
        host.run(['btrfs', 'subvolume', 'snapshot', '-r', source or host.path('/'), directory / 'snapshot'])
    except UndoError:
        with contextlib.suppress(OSError):
            directory.rmdir()
        raise
    info = {'schema': SCHEMA, 'id': identifier, 'kind': kind, 'reason': reason, 'created': stamp(host),
            'kernel': host.release, 'boot': {'kernels': boot_kernels(directory / 'snapshot')},
            'pre_id': None, 'post_id': None, 'command': None, 'exit_code': None,
            'packages': None, 'planned': None, 'protected': False}
    info.update(extra)
    write_json(directory / 'info.json', info)
    refresh_grub(host, cfg)
    return info


def update_info(host, identifier, **changes):
    path = snapshot_dir(host, identifier) / 'info.json'
    info = read_json(path, {})
    info.update(changes)
    write_json(path, info)


def delete_snapshot(host, identifier):
    directory = snapshot_dir(host, identifier)
    host.run(['btrfs', 'subvolume', 'delete', directory / 'snapshot'])
    with contextlib.suppress(OSError):
        (directory / 'info.json').unlink()
    with contextlib.suppress(OSError):
        directory.rmdir()


