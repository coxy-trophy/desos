def pending_path(host):
    return host.path(STATE + '/pending.json')


def active_run(host):
    """True while a `desos-undo run` wrapper owns the open transaction."""
    pending = read_json(pending_path(host))
    return bool(pending and pending.get('source') == 'run' and pending.get('boot_id') == host.boot_id()
                and host.pid_alive(pending.get('pid') or 0))


def transaction_pre(host, cfg, source, reason, planned=None, command=None):
    info = create_snapshot(host, cfg, 'pre', reason, planned=planned, command=command)
    write_json(pending_path(host), {'source': source, 'pre_id': info['id'], 'started': stamp(host), 'reason': reason,
                                    'pid': host.pid, 'boot_id': host.boot_id()})
    return info


def transaction_post(host, cfg, exit_code=None):
    pending = read_json(pending_path(host))
    if not pending:
        return None
    pre_id = pending['pre_id']
    changes = package_diff(dpkg_packages(snapshot_tree(host, pre_id)), dpkg_packages(host.path('/')))
    empty = not any(changes.values())
    with contextlib.suppress(OSError):
        pending_path(host).unlink()
    if empty and pending['source'] == 'dpkg':
        with contextlib.suppress(UndoError):
            delete_snapshot(host, pre_id)
        refresh_grub(host, cfg)
        return None
    reason = 'after: ' + (pending.get('reason') or '').replace('before: ', '', 1)
    info = create_snapshot(host, cfg, 'post', reason, pre_id=pre_id, packages=changes, exit_code=exit_code)
    with contextlib.suppress(OSError):
        update_info(host, pre_id, post_id=info['id'], packages=changes, exit_code=exit_code)
    with contextlib.suppress(UndoError, OSError):
        prune(host, cfg)
    return info


