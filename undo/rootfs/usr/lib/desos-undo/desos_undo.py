def load_config(host):
    parser = configparser.ConfigParser(interpolation=None)
    parser.read_dict(DEFAULTS)
    try:
        parser.read(host.path('/etc/desos-undo.conf'))
    except configparser.Error as error:
        print('desos-undo: ignoring invalid /etc/desos-undo.conf: %s' % error, file=sys.stderr)
    return parser


def cfg_int(cfg, section, key, minimum=0):
    try:
        return max(minimum, int(cfg.get(section, key)))
    except ValueError:
        return max(minimum, int(DEFAULTS[section][key]))


def findmnt(host, mountpoint):
    done = host.run(['findmnt', '-J', '-o', 'TARGET,SOURCE,FSTYPE,UUID,FSROOT', '-M', mountpoint], check=False)
    if done.returncode != 0:
        return None
    try:
        entries = json.loads(done.stdout).get('filesystems') or []
    except (ValueError, AttributeError):
        return None
    return entries[-1] if entries else None


class Probe:
    """What this machine can do. `supported` is False in a live session, on a
    non-btrfs root, or on a btrfs layout that is not the DesOS one."""

    def __init__(self):
        self.supported = False
        self.code = self.message = None
        self.live = False
        self.fstype = self.uuid = self.device = self.subvolume = None
        self.booted_snapshot = None
        self.pending_reboot = False

    def fail(self, code, message):
        self.supported, self.code, self.message = False, code, message
        return self


def probe(host, cfg):
    result = Probe()
    if 'boot=casper' in host.cmdline():
        result.live = True
        return result.fail('live-session', 'This is the DesOS live session: nothing is installed, so there is nothing to undo.')
    root = findmnt(host, '/')
    if not root:
        return result.fail('layout-unsupported', 'The root filesystem could not be inspected (findmnt failed).')
    result.fstype, result.uuid = root.get('fstype'), root.get('uuid')
    result.device = (root.get('source') or '').split('[')[0] or None
    result.subvolume = root.get('fsroot')
    if result.fstype != 'btrfs':
        return result.fail('not-btrfs', 'The system is installed on %s, not btrfs: snapshots and rollback are unavailable.' % (result.fstype or 'an unknown filesystem'))
    if not host.which('btrfs'):
        return result.fail('tools-missing', 'The btrfs tool (package btrfs-progs) is not installed.')
    root_sub = '/' + cfg.get('layout', 'root_subvolume')
    snap_sub = '/' + cfg.get('layout', 'snapshots_subvolume')
    match = re.fullmatch(re.escape(snap_sub) + r'/(\d+)/snapshot', result.subvolume or '')
    if match:
        result.booted_snapshot = int(match.group(1))
    elif (result.subvolume or '').startswith(root_sub + '.desos-undo-'):
        result.pending_reboot = True
    elif result.subvolume != root_sub:
        return result.fail('layout-unsupported', 'The root filesystem is btrfs subvolume %s; DesOS undo needs %s.' % (result.subvolume, root_sub))
    snaps = findmnt(host, SNAPSHOTS)
    if not snaps or snaps.get('fstype') != 'btrfs' or snaps.get('uuid') != result.uuid or snaps.get('fsroot') != snap_sub:
        return result.fail('layout-unsupported', '%s is not the %s subvolume of the root filesystem.' % (SNAPSHOTS, snap_sub))
    result.supported = True
    return result


def require(host, cfg, writable_root=False):
    found = probe(host, cfg)
    if not found.supported:
        raise UndoError(found.message, found.code, supported=False)
    if writable_root and found.booted_snapshot is not None:
        raise UndoError('The system is running read-only from snapshot %d. Use "desos-undo rollback %d" to keep it, then restart.'
                        % (found.booted_snapshot, found.booted_snapshot), 'snapshot-boot')
    if writable_root and found.pending_reboot:
        raise UndoError('A rollback is waiting for a restart. Restart before making new snapshots.', 'restart-pending')
    return found


def require_root(host):
    if host.euid != 0:
        raise UndoError('This command needs administrator rights (run it with sudo).', 'not-root')


