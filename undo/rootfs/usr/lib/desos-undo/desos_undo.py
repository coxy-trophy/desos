def version_key(text):
    return [int(part) if part.isdigit() else part for part in re.split(r'(\d+)', text)]


def _order(text, index):
    if index >= len(text) or text[index].isdigit():
        return 0
    char = text[index]
    if char == '~':
        return -1
    return ord(char) if char.isalpha() else ord(char) + 256


def _compare_part(left, right):
    i = j = 0
    while i < len(left) or j < len(right):
        while (i < len(left) and not left[i].isdigit()) or (j < len(right) and not right[j].isdigit()):
            a, b = _order(left, i), _order(right, j)
            if a != b:
                return -1 if a < b else 1
            i, j = i + 1, j + 1
        start_i, start_j = i, j
        while i < len(left) and left[i].isdigit():
            i += 1
        while j < len(right) and right[j].isdigit():
            j += 1
        a, b = int(left[start_i:i] or 0), int(right[start_j:j] or 0)
        if a != b:
            return -1 if a < b else 1
    return 0


def compare_versions(left, right):
    """Debian version ordering (deb-version(7)); returns -1, 0 or 1."""
    def split(version):
        epoch, rest = version.split(':', 1) if ':' in version else ('0', version)
        upstream, revision = rest.rsplit('-', 1) if '-' in rest else (rest, '')
        return (int(epoch) if epoch.isdigit() else 0), upstream, revision
    a, b = split(left), split(right)
    if a[0] != b[0]:
        return -1 if a[0] < b[0] else 1
    return _compare_part(a[1], b[1]) or _compare_part(a[2], b[2])


def dpkg_packages(tree):
    """Installed packages of a filesystem tree, read from its dpkg database."""
    try:
        text = (Path(tree) / 'var/lib/dpkg/status').read_text(errors='replace')
    except OSError:
        return {}
    packages = {}
    for block in text.split('\n\n'):
        fields = dict(re.findall(r'^(Package|Status|Version|Architecture): (.*)$', block, re.M))
        if fields.get('Status', '').split()[-1:] != ['installed'] or 'Package' not in fields:
            continue
        name = fields['Package']
        if name in packages:
            name += ':' + fields.get('Architecture', '?')
        packages[name] = fields.get('Version', '')
    return packages


def package_diff(before, after):
    result = {'installed': [], 'removed': [], 'upgraded': [], 'downgraded': []}
    for name in sorted(set(before) | set(after)):
        old, new = before.get(name), after.get(name)
        if old is None:
            result['installed'].append({'name': name, 'version': new})
        elif new is None:
            result['removed'].append({'name': name, 'version': old})
        elif old != new:
            key = 'upgraded' if compare_versions(old, new) < 0 else 'downgraded'
            result[key].append({'name': name, 'from': old, 'to': new})
    return result


def package_summary(changes):
    parts = []
    for key in ('installed', 'upgraded', 'downgraded', 'removed'):
        names = [item['name'] for item in changes.get(key, [])]
        if names:
            more = ' (+%d more)' % (len(names) - 3) if len(names) > 3 else ''
            parts.append('%s %s%s' % (key, ', '.join(names[:3]), more))
    return '; '.join(parts) or 'no package changes'


def parse_apt_plan(text):
    """DPkg::Pre-Install-Pkgs protocol version 2 or 3 as written by apt."""
    lines = text.splitlines()
    if lines and lines[0].startswith('VERSION'):
        lines = lines[lines.index('') + 1:] if '' in lines else []
    plan = {'installed': [], 'upgraded': [], 'downgraded': [], 'removed': []}
    seen = set()
    for line in lines:
        fields = line.split()
        if len(fields) >= 9:
            name, old, relation, new, action = fields[0], fields[1], fields[4], fields[5], fields[8]
        elif len(fields) >= 5:
            name, old, relation, new, action = fields[:5]
        else:
            continue
        if name in seen:
            continue
        if action == '**REMOVE**' or new == '-':
            plan['removed'].append({'name': name, 'version': old})
        elif old == '-':
            plan['installed'].append({'name': name, 'version': new})
        elif relation == '<':
            plan['upgraded'].append({'name': name, 'from': old, 'to': new})
        elif relation == '>':
            plan['downgraded'].append({'name': name, 'from': old, 'to': new})
        else:
            continue
        seen.add(name)
    return plan


def _walk(tree, relative):
    """Entries below tree/relative without following symlinks or crossing into
    other filesystems (nested subvolumes and mounts are not part of a snapshot)."""
    found = {}
    start = Path(tree) / relative.lstrip('/')
    try:
        first = os.lstat(start)
    except OSError:
        return found
    found[relative.rstrip('/') or '/'] = first
    if not stat.S_ISDIR(first.st_mode):
        return found
    pending = [(start, relative.rstrip('/'))]
    while pending and len(found) < WALK_CAP:
        directory, name = pending.pop()
        try:
            entries = sorted(os.scandir(directory), key=lambda entry: entry.name)
        except OSError:
            continue
        for entry in entries:
            info = entry.stat(follow_symlinks=False)
            path = name + '/' + entry.name
            found[path] = info
            if stat.S_ISDIR(info.st_mode) and info.st_dev == first.st_dev:
                pending.append((Path(entry.path), path))
    return found


def tree_diff(before, after, paths, limit):
    added, removed, modified, capped = [], [], [], False
    for relative in paths:
        old, new = _walk(before, relative), _walk(after, relative)
        capped = capped or len(old) >= WALK_CAP or len(new) >= WALK_CAP
        for path in sorted(set(old) | set(new)):
            a, b = old.get(path), new.get(path)
            if a is None:
                added.append(path)
            elif b is None:
                removed.append(path)
            elif _changed(Path(before) / path.lstrip('/'), a, Path(after) / path.lstrip('/'), b):
                modified.append(path)
    return {'added': added[:limit], 'removed': removed[:limit], 'modified': modified[:limit],
            'truncated': capped or any(len(group) > limit for group in (added, removed, modified))}


def _changed(left, a, right, b):
    if stat.S_IFMT(a.st_mode) != stat.S_IFMT(b.st_mode):
        return True
    if (a.st_mode, a.st_uid, a.st_gid) != (b.st_mode, b.st_uid, b.st_gid):
        return True
    if stat.S_ISLNK(a.st_mode):
        return os.readlink(left) != os.readlink(right)
    if not stat.S_ISREG(a.st_mode):
        return False
    if a.st_size != b.st_size:
        return True
    if a.st_mtime_ns == b.st_mtime_ns:
        return False
    try:
        return not filecmp.cmp(left, right, shallow=False)
    except OSError:
        return True


