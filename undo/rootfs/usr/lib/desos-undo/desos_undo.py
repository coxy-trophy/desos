def session_state(host, cfg):
    """(ready, token). The token changes if the greeter restarts, so two equal
    ready samples mean it stayed up."""
    default = host.run(['systemctl', 'get-default'], check=False).stdout.strip()
    enabled = host.run(['systemctl', 'is-enabled', 'greetd.service'], check=False).stdout.strip()
    if default != 'graphical.target' or not enabled.startswith(('enabled', 'static', 'alias', 'indirect')):
        state = host.run(['systemctl', 'is-system-running'], check=False).stdout.strip()
        return state in ('running', 'degraded'), 'system'
    shown = host.run(['systemctl', 'show', 'greetd.service', '--property=ActiveState,SubState,NRestarts,MainPID'], check=False).stdout
    values = dict(line.split('=', 1) for line in shown.splitlines() if '=' in line)
    if values.get('ActiveState') != 'active' or values.get('SubState') != 'running':
        return False, None
    if cfg.get('boot', 'require_session').strip().lower() in ('yes', 'true', '1'):
        sessions = host.run(['loginctl', 'list-sessions', '--no-legend'], check=False).stdout
        if not sessions.strip():
            return False, None
    return True, 'greetd:%s:%s' % (values.get('NRestarts'), values.get('MainPID'))


def wait_until_good(host, cfg, wait):
    deadline = host.now() + cfg_int(cfg, 'boot', 'good_timeout_seconds')
    stable = cfg_int(cfg, 'boot', 'good_stable_seconds')
    while True:
        ready, token = session_state(host, cfg)
        if ready:
            host.sleep(stable)
            if session_state(host, cfg) == (True, token):
                return True
        if not wait or host.now() >= deadline:
            return False
        host.sleep(5)


def mark_good(host, cfg, found):
    arming = boot_arming(host)
    snapshots = list_snapshots(host)
    good = read_json(host.path(STATE + '/good.json'), {}).get('id')
    newest = snapshots[-1]['id'] if snapshots else None
    rollback_record = read_json(host.path(STATE + '/rollback.json'))
    data = {'good_id': good, 'new_snapshot': False, 'removed_roots': [], 'warnings': []}
    try:
        data['removed_roots'] = cleanup_retired_roots(host, cfg, found)
    except (UndoError, OSError) as error:
        data['warnings'].append('Old system copies could not be removed: %s' % error)
    if good is None or good not in [info['id'] for info in snapshots] or newest != good or rollback_record:
        try:
            info = create_snapshot(host, cfg, 'boot-good', 'the system started and reached the sign-in screen')
            good, data['new_snapshot'] = info['id'], True
        except (UndoError, OSError) as error:
            data['warnings'].append('No new known-good snapshot: %s' % error)
    if good is not None:
        write_json(host.path(STATE + '/good.json'), {'id': good, 'time': stamp(host)})
    with contextlib.suppress(OSError):
        host.path(STATE + '/rollback.json').unlink()
    try:
        changes = {'undo_tries': 0, 'undo_healed': ''}
        if good is not None:
            changes['undo_good'] = good
        update_env(host, arming, **changes)
    except (OSError, UndoError) as error:
        data['warnings'].append('Boot counter could not be reset: %s' % error)
    refresh_grub(host, cfg)
    with contextlib.suppress(UndoError, OSError):
        prune(host, cfg)
    marker = host.runtime / 'boot-good'
    with contextlib.suppress(OSError):
        marker.parent.mkdir(parents=True, exist_ok=True)
        marker.write_text(stamp(host) + '\n')
    data['good_id'], data['mode'] = good, arming['mode']
    return data


def boot_start(host, cfg, found):
    """Early in every boot: count the attempt where GRUB cannot, and finish an
    automatic recovery when GRUB started the last known-good snapshot."""
    arming = boot_arming(host)
    tokens = host.cmdline()
    data = {'mode': arming['mode'], 'action': 'none', 'snapshot': found.booted_snapshot}
    env = read_env(host.path(arming['env'])) if arming['env'] else {}
    tries = int(env['undo_tries']) if env.get('undo_tries', '').isdigit() else 0
    neutral = bool(NEUTRAL_BOOT & set(tokens)) or any(token.startswith('systemd.unit=') for token in tokens)
    if found.booted_snapshot is not None and 'desos.undo.heal=1' in tokens:
        target = found.booted_snapshot
        update_env(host, arming, undo_healed=target)
        threshold = arming['threshold'] or cfg_int(cfg, 'boot', 'failure_threshold', 1)
        record = rollback(host, cfg, found, target, 'automatic recovery after %d failed starts' % threshold, automatic=True)
        update_env(host, arming, undo_tries=0)
        undo_text = (' The state that failed to start is kept as snapshot %d: "desos-undo diff %d" shows what differed and '
                     '"sudo desos-undo rollback %d" returns to it.' % ((record['undo'],) * 3)) if record['undo'] else ''
        add_notice(host, 'auto-recovery',
                   'DesOS did not start %d times in a row, so it went back to the last working state (snapshot %d). '
                   'Your personal files were not changed.%s' % (threshold, target, undo_text),
                   snapshot=target, undo=record['undo'])
        host.run(['systemctl', '--no-block', 'reboot'], check=False)
        data.update(action='healed', rollback=record)
    elif found.booted_snapshot is not None or neutral:
        # A deliberate snapshot or rescue start is not evidence of a broken system.
        if arming['mode'] == 'grub-counted' and tries:
            update_env(host, arming, undo_tries=tries - 1)
        data['action'] = 'not-counted'
    elif arming['mode'] == 'userspace-counted' and not found.pending_reboot:
        update_env(host, arming, undo_tries=min(tries + 1, 99))
        data['action'] = 'counted'
    return data


