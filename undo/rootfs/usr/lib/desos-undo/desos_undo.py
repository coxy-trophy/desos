@contextlib.contextmanager
def toplevel(host, found):
    """The btrfs top level (subvolid 5), where @ and its siblings live."""
    mountpoint = host.runtime / 'top'
    mountpoint.mkdir(parents=True, exist_ok=True)
    source = found.device or ('UUID=' + found.uuid)
    host.run(['mount', '-t', 'btrfs', '-o', 'subvolid=5', source, mountpoint])
    try:
        yield mountpoint
    finally:
        host.run(['umount', mountpoint], check=False)


def exchange(left, right):
    """Atomically swap two names (renameat2 RENAME_EXCHANGE); False if unsupported."""
    try:
        libc = ctypes.CDLL(None, use_errno=True)
        return libc.renameat2(-100, os.fsencode(str(left)), -100, os.fsencode(str(right)), 2) == 0
    except (OSError, AttributeError):
        return False


def sync_grub_modules(old_root, new_root):
    """Keep the GRUB modules that match the installed boot code: the core image
    in the MBR/ESP is not part of any snapshot and must find matching modules."""
    copied = []
    for platform in ('i386-pc', 'x86_64-efi'):
        source, target = Path(old_root) / 'boot/grub' / platform, Path(new_root) / 'boot/grub' / platform
        if source.is_dir() and not source.is_symlink() and target.parent.is_dir():
            if target.exists():
                shutil.rmtree(target)
            shutil.copytree(source, target, symlinks=True)
            copied.append(platform)
    return copied


def rollback(host, cfg, found, target, reason, automatic=False):
    get_snapshot(host, target)
    root_name = cfg.get('layout', 'root_subvolume')
    snaps_name = cfg.get('layout', 'snapshots_subvolume')
    warnings = []
    with toplevel(host, found) as top:
        current, staged = top / root_name, top / (root_name + '.desos-undo-new')
        source = top / snaps_name / str(target) / 'snapshot'
        if not source.is_dir():
            raise UndoError('Snapshot %d is missing on disk.' % target, 'no-such-snapshot')
        undo = None
        if current.is_dir():
            undo = create_snapshot(host, cfg, 'rollback', 'state before going back to snapshot %d (%s)' % (target, reason),
                                   source=current, rolled_back_to=target, automatic=automatic)
        else:
            warnings.append('The current system subvolume was missing, so there is no undo point for this rollback.')
        if staged.exists():
            host.run(['btrfs', 'subvolume', 'delete', staged])
        host.run(['btrfs', 'subvolume', 'snapshot', source, staged])
        if current.is_dir():
            try:
                copied = sync_grub_modules(current, staged)
            except OSError as error:
                copied = []
                warnings.append('Boot loader modules could not be carried over: %s' % error)
            retired = top / ('%s.desos-undo-old-%d' % (root_name, undo['id']))
            if exchange(current, staged):
                os.rename(staged, retired)
            else:
                os.rename(current, retired)
                os.rename(staged, current)
        else:
            copied = []
            os.rename(staged, current)
        host.run(['btrfs', 'filesystem', 'sync', top], check=False)
    record = {'target': target, 'undo': undo['id'] if undo else None, 'time': stamp(host), 'reason': reason,
              'automatic': automatic, 'grub_modules': copied, 'warnings': warnings}
    write_json(host.path(STATE + '/rollback.json'), record)
    return record


def cleanup_retired_roots(host, cfg, found):
    """Delete the replaced root subvolumes left behind by earlier rollbacks."""
    root_name = cfg.get('layout', 'root_subvolume')
    removed = []
    with toplevel(host, found) as top:
        for path in sorted(top.glob(root_name + '.desos-undo-*')):
            if '/' + path.name == found.subvolume or not path.is_dir():
                continue
            if host.run(['btrfs', 'subvolume', 'delete', path], check=False).returncode == 0:
                removed.append(path.name)
    return removed


