class UndoError(Exception):
    def __init__(self, message, code='error', supported=True):
        super().__init__(message)
        self.code, self.supported = code, supported


class Completed:
    def __init__(self, returncode, stdout='', stderr=''):
        self.returncode, self.stdout, self.stderr = returncode, stdout, stderr


def _real_runner(argv, input_text=None):
    try:
        done = subprocess.run(argv, input=input_text, capture_output=True, text=True)
    except FileNotFoundError:
        return Completed(127, '', argv[0] + ': not found')
    return Completed(done.returncode, done.stdout, done.stderr)


def _real_execute(argv):
    try:
        return subprocess.call(argv)
    except FileNotFoundError:
        print('desos-undo: %s: command not found' % argv[0], file=sys.stderr)
        return 127
    except PermissionError:
        print('desos-undo: %s: permission denied' % argv[0], file=sys.stderr)
        return 126


class Host:
    """Everything the tool touches outside its own process."""

    def __init__(self, root='/', runner=None, clock=None, sleeper=None, euid=None,
                 release=None, environ=None, execute=None, which=None, usage=None, runtime=None):
        self.root = Path(root)
        self.runtime = Path(runtime) if runtime else self.root / 'run/desos-undo'
        self._runner = runner or _real_runner
        self.now = clock or time.time
        self.sleep = sleeper or time.sleep
        self.euid = os.geteuid() if euid is None else euid
        self.release = release if release is not None else os.uname().release
        self.environ = os.environ if environ is None else environ
        self.execute = execute or _real_execute
        self.pid = os.getpid()
        self.which = which or shutil.which
        self.usage = usage or shutil.disk_usage

    def path(self, absolute):
        return self.root / str(absolute).lstrip('/')

    def run(self, argv, check=True, input_text=None):
        done = self._runner([str(item) for item in argv], input_text)
        if check and done.returncode != 0:
            detail = (done.stderr or done.stdout or '').strip().splitlines()
            raise UndoError('%s failed (%d): %s' % (argv[0], done.returncode, detail[-1] if detail else 'no output'),
                            'command-failed')
        return done

    def boot_id(self):
        try:
            return self.path('/proc/sys/kernel/random/boot_id').read_text().strip()
        except OSError:
            return ''

    def pid_alive(self, pid):
        return self.path('/proc/%d' % pid).exists()

    def cmdline(self):
        try:
            return self.path('/proc/cmdline').read_text().split()
        except OSError:
            return []


