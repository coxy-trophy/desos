def protected_ids(host):
    keep = set()
    for name in ('good.json', 'pending.json', 'rollback.json'):
        record = read_json(host.path(STATE + '/' + name), {})
        keep.update(value for key, value in record.items() if key in ('id', 'pre_id', 'target', 'undo') and isinstance(value, int))
    return keep


def prune(host, cfg, dry_run=False):
    snapshots = list_snapshots(host)
    keep = protected_ids(host) | {info['id'] for info in snapshots if info.get('protected')}
    goods = [info['id'] for info in snapshots if info.get('kind') == 'boot-good']
    keep.update(goods[-1:])
    doomed = {}

    def trim(ids, count, why):
        for identifier in ids[:max(0, len(ids) - count)]:
            doomed.setdefault(identifier, why)

    pairs = {}
    for info in snapshots:
        if info.get('kind') == 'pre':
            pairs.setdefault(info['id'], []).append(info['id'])
        elif info.get('kind') == 'post':
            pairs.setdefault(info.get('pre_id') or info['id'], []).append(info['id'])
    order = sorted(pairs)
    for key in order[:max(0, len(order) - cfg_int(cfg, 'retention', 'keep_pairs'))]:
        for identifier in pairs[key]:
            doomed.setdefault(identifier, 'older than the newest %d transactions' % cfg_int(cfg, 'retention', 'keep_pairs'))
    for kind, option in (('manual', 'keep_manual'), ('boot-good', 'keep_boot_good'), ('rollback', 'keep_rollback')):
        trim([info['id'] for info in snapshots if info.get('kind') == kind], cfg_int(cfg, 'retention', option),
             'more than %d %s snapshots' % (cfg_int(cfg, 'retention', option), kind))
    days = cfg_int(cfg, 'retention', 'max_age_days')
    if days:
        limit = time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(host.now() - days * 86400))
        for info in snapshots:
            if info.get('created') and info['created'] < limit:
                doomed.setdefault(info['id'], 'older than %d days' % days)
    for identifier in keep:
        doomed.pop(identifier, None)
    minimum = cfg_int(cfg, 'retention', 'min_free_percent')
    try:
        usage = host.usage(host.path(SNAPSHOTS))
        low = minimum and usage.total and usage.free * 100 < usage.total * minimum
    except OSError:
        low = False
    if low:
        # Space returns asynchronously on btrfs, so free it gradually.
        spare = [info['id'] for info in snapshots if info['id'] not in keep and info['id'] not in doomed]
        for identifier in spare[:3]:
            doomed[identifier] = 'free space below %d%%' % minimum
    deleted, failed = [], []
    for identifier in sorted(doomed):
        if dry_run:
            deleted.append(identifier)
            continue
        try:
            delete_snapshot(host, identifier)
            deleted.append(identifier)
        except UndoError as error:
            failed.append({'id': identifier, 'error': str(error)})
    if deleted and not dry_run:
        refresh_grub(host, cfg)
    return {'deleted': deleted, 'failed': failed, 'dry_run': dry_run,
            'reasons': {str(identifier): doomed[identifier] for identifier in deleted},
            'kept': len(snapshots) - (0 if dry_run else len(deleted))}


