# GRUB: static fragment for grub.cfg and the dynamic snapshot menu

def grub_quote(text):
    cleaned = ''.join(char if 32 <= ord(char) < 127 and char not in "'\\" else ' ' for char in str(text))
    return "'" + cleaned[:90] + "'"


def grub_fragment(host, cfg):
    """Text for /etc/grub.d/42_desos-undo. Depends only on the mount layout,
    never on the live-session check: Calamares generates the installed
    system's grub.cfg from inside the live session."""
    root_sub = '/' + cfg.get('layout', 'root_subvolume')
    snap_sub = '/' + cfg.get('layout', 'snapshots_subvolume')
    root, snaps = findmnt(host, '/'), findmnt(host, SNAPSHOTS)
    reason = None
    if not root or root.get('fstype') != 'btrfs':
        reason = 'the root filesystem is not btrfs'
    elif root.get('fsroot') != root_sub or not snaps or snaps.get('fsroot') != snap_sub or snaps.get('uuid') != root.get('uuid'):
        reason = 'the btrfs layout is not %s plus %s' % (root_sub, snap_sub)
    elif not re.fullmatch(r'[0-9A-Fa-f-]+', root.get('uuid') or ''):
        reason = 'the root filesystem UUID is unknown'
    if reason:
        return '# desos-undo: self-healing boot and the snapshot menu are inactive: %s\n' % reason
    threshold = cfg_int(cfg, 'boot', 'failure_threshold', 1)
    esp = findmnt(host, ESP)
    writable = bool(esp and esp.get('fstype') == 'vfat' and re.fullmatch(r'[0-9A-Fa-f-]+', esp.get('uuid') or ''))
    mode = 'grub-counted' if writable else 'userspace-counted'
    env_path = ESP_ENV if writable else STATE + '/grub/env'
    lines = ['### desos-undo: self-healing boot and snapshot menu',
             '# desos-undo: mode=%s env=%s threshold=%d' % (mode, env_path, threshold),
             'set desos_undo_action=none',
             'if search --no-floppy --fs-uuid --set=desos_undo_dev %s; then' % root['uuid'],
             '  set desos_undo_state="(${desos_undo_dev})%s/.desos-undo/grub"' % snap_sub,
             '  set desos_undo_env=""']
    if writable:
        lines += ['  if search --no-floppy --fs-uuid --set=desos_undo_envdev %s; then' % esp['uuid'],
                  '    set desos_undo_env="(${desos_undo_envdev})%s"' % ESP_ENV[len(ESP):],
                  '  fi']
    else:
        lines += ['  set desos_undo_env="${desos_undo_state}/env"']
    lines += ['  if [ -n "${desos_undo_env}" ]; then',
              '    if [ -s "${desos_undo_env}" ]; then',
              '      set desos_undo_action=count',
              '      load_env -f "${desos_undo_env}" undo_tries undo_good undo_healed',
              '      if [ -z "${undo_tries}" ]; then set undo_tries=0; fi',
              '      if [ -n "${undo_good}" ]; then',
              '        if [ "${undo_tries}" -ge %d ]; then' % threshold,
              '          if [ -z "${undo_healed}" ]; then',
              '            set desos_undo_action=heal',
              '          else',
              '            set desos_undo_action=menu',
              '          fi',
              '        fi',
              '      fi']
    if writable:
        lines += ['      if [ "${desos_undo_action}" = "count" ]; then']
        for value in range(threshold):
            lines += ['        %s [ "${undo_tries}" = "%d" ]; then' % ('if' if value == 0 else 'elif', value),
                      '          set undo_tries=%d' % (value + 1)]
        lines += ['        else',
                  '          set undo_tries=%d' % threshold,
                  '        fi',
                  '        save_env -f "${desos_undo_env}" undo_tries',
                  '      fi',
                  '      if [ "${desos_undo_action}" = "heal" ]; then',
                  '        set undo_healed="${undo_good}"',
                  '        save_env -f "${desos_undo_env}" undo_healed',
                  '      fi']
    lines += ['    fi',
              '  fi',
              '  if [ -s "${desos_undo_state}/snapshots.cfg" ]; then',
              '    source "${desos_undo_state}/snapshots.cfg"',
              '  fi',
              '  if [ "${desos_undo_action}" = "heal" ]; then',
              '    set default="desos-undo-heal"',
              '    set timeout_style=menu',
              '    set timeout=10',
              '  fi',
              '  if [ "${desos_undo_action}" = "menu" ]; then',
              '    set default="desos-undo-snapshots"',
              '    set timeout_style=menu',
              '    set timeout=-1',
              '  fi',
              'fi',
              '### end desos-undo']
    return '\n'.join(lines) + '\n'


def _entry(title, identifier, uuid, snap_sub, info, kernel, extra, indent):
    base = '%s/%d/snapshot' % (snap_sub, info['id'])
    arguments = ' '.join(['root=UUID=' + uuid, 'ro', 'rootflags=subvol=' + base.lstrip('/')] + extra)
    # Icon classes are defined by the boot theme (boot-theme/README.md).
    icon = 'desos-known-good' if identifier == 'desos-undo-heal' else 'desos-snapshot'
    body = ['menuentry %s --class %s --id %s {' % (grub_quote(title), icon, identifier),
            '  insmod gzio', '  insmod part_gpt', '  insmod part_msdos', '  insmod btrfs',
            '  search --no-floppy --fs-uuid --set=root %s' % uuid,
            '  echo %s' % grub_quote('Starting DesOS snapshot %d ...' % info['id']),
            '  linux %s/boot/vmlinuz-%s %s' % (base, kernel, arguments),
            '  initrd %s/boot/initrd.img-%s' % (base, kernel),
            '}']
    return [indent + line for line in body]


def grub_snapshots(host, cfg, uuid):
    snap_sub = '/' + cfg.get('layout', 'snapshots_subvolume')
    keep = [token for token in host.cmdline()
            if SAFE_TOKEN.fullmatch(token) and token not in ('ro', 'rw')
            and not token.startswith(('BOOT_IMAGE=', 'root=', 'rootflags=', 'initrd=', 'desos.undo.'))]
    bootable = [info for info in list_snapshots(host) if preferred_kernel(info) and SAFE_TOKEN.fullmatch(preferred_kernel(info))]
    lines = ['# Written by desos-undo; regenerated whenever snapshots change. Do not edit.',
             'set desos_undo_menu=%d' % len(bootable)]
    good = read_json(host.path(STATE + '/good.json'), {}).get('id')
    for info in bootable:
        if info['id'] == good:
            lines += ['if [ "${desos_undo_action}" = "heal" ]; then']
            lines += _entry('DesOS did not start: recovering the last working system (snapshot %d)' % good,
                            'desos-undo-heal', uuid, snap_sub, info, preferred_kernel(info),
                            keep + ['desos.undo.snapshot=%d' % good, 'desos.undo.heal=1'], '  ')
            lines += ['fi']
    if bootable:
        lines += ["submenu 'DesOS snapshots (start an earlier system state)' --class desos-snapshots --id desos-undo-snapshots {"]
        for info in reversed(bootable[-cfg_int(cfg, 'boot', 'menu_entries', 1):]):
            title = 'Snapshot %d  %s  %s: %s' % (info['id'], (info.get('created') or '')[:16].replace('T', ' '),
                                                 info.get('kind'), info.get('reason') or '')
            lines += _entry(title, 'desos-undo-snapshot-%d' % info['id'], uuid, snap_sub, info, preferred_kernel(info),
                            keep + ['desos.undo.snapshot=%d' % info['id']], '  ')
        lines += ['}']
    return '\n'.join(lines) + '\n'


def refresh_grub(host, cfg):
    """Best effort: a menu that cannot be written must never fail a snapshot."""
    try:
        root = findmnt(host, '/')
        if root and re.fullmatch(r'[0-9A-Fa-f-]+', root.get('uuid') or ''):
            write_text(host.path(STATE + '/grub/snapshots.cfg'), grub_snapshots(host, cfg, root['uuid']))
            return True
    except (OSError, UndoError) as error:
        print('desos-undo: could not refresh the snapshot boot menu: %s' % error, file=sys.stderr)
    return False


