def build_fonts(out):
    for file, size, family in FONT_FILES.values():
        name = font_name(size, family)
        target = out / (f'{family} {size}'.lower().replace(' ', '_') + '.pf2')
        subprocess.run(['grub-mkfont', '--output', str(target), '--size', str(size), '--name', family,
                        '--range', GLYPHS, str(FONTS / file)], check=True)
        # The theme asks for fonts by name; a renamed face must fail here.
        if name.encode() not in target.read_bytes()[:512]:
            raise SystemExit(f'{target.name}: PF2 font is not named "{name}"')


def save(image, path):
    # No ancillary chunks (timestamps, software) so identical pixels are identical bytes.
    image.save(path, format='PNG', optimize=False, compress_level=9)


def solid(colour, size=(1, 1)):
    from PIL import Image
    return Image.new('RGBA', size, colour + (255,))


def slices(out, stem, image, left, top, right, bottom):
    """Cut an image into GRUB's nine styled-box slices."""
    width, height = image.size
    columns = [('w', 0, left), ('', left, width - right), ('e', width - right, width)]
    rows = [('n', 0, top), ('', top, height - bottom), ('s', height - bottom, height)]
    for row, y0, y1 in rows:
        for column, x0, x1 in columns:
            if x1 <= x0 or y1 <= y0:
                continue
            save(image.crop((x0, y0, x1, y1)), out / f'{stem}_{(row + column) or "c"}.png')


def rounded_box(size, radius, fill, outline, scale=4):
    from PIL import Image, ImageDraw
    big = Image.new('RGBA', (size * scale, size * scale), (0, 0, 0, 0))
    draw = ImageDraw.Draw(big)
    draw.rounded_rectangle((0, 0, size * scale - 1, size * scale - 1), radius * scale, fill=outline + (255,))
    draw.rounded_rectangle((scale, scale, size * scale - 1 - scale, size * scale - 1 - scale),
                           (radius - 1) * scale, fill=fill + (255,))
    return big.resize((size, size), Image.LANCZOS)


def build_boxes(out):
    from PIL import Image, ImageDraw
    save(solid(LINE), out / 'line.png')

    # The editor and command line open in a frame card: panel fill, hairline
    # outline, 8px corners.
    slices(out, 'terminal', rounded_box(48, 8, PANEL, LINE), 16, 16, 16, 16)

    # Selection: a quiet tint with a solid accent bar on the left edge.
    select = Image.new('RGBA', (16, 12), SELECT_EDGE + (255,))
    draw = ImageDraw.Draw(select)
    draw.rectangle((1, 1, 14, 10), fill=SELECT_FILL + (255,))
    draw.rectangle((0, 0, 2, 11), fill=ACCENT + (255,))
    slices(out, 'select', select, 8, 1, 4, 1)

    # Countdown bar: a thin meter, as the desktop's volume and memory meters.
    for stem, colour in (('bar', TRACK), ('bar_fill', ACCENT)):
        band = Image.new('RGBA', (1, BAR_BOX), (0, 0, 0, 0))
        band.paste(colour + (255,), (0, BAR_ROW, 1, BAR_ROW + BAR_HEIGHT))
        save(band, out / f'{stem}_c.png')

    save(solid(TRACK), out / 'scroll_frame_c.png')
    save(solid(mix(TRACK, ACCENT, 0.72)), out / 'scroll_thumb_c.png')


def build_wordmark(out):
    from PIL import Image, ImageDraw, ImageFont
    face = ImageFont.truetype(str(FONTS / 'ChakraPetch-SemiBold.ttf'), 38)
    small = ImageFont.truetype(str(FONTS / 'JetBrainsMono.ttf'), 11)
    des, os_ = face.getlength('Des'), face.getlength('OS')
    pad_x, height = 20, 60
    width = round(pad_x * 2 + des + os_)
    image = Image.new('RGBA', (width + 190, height), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)
    baseline = 43
    draw.text((pad_x, baseline), 'Des', font=face, fill=TEXT + (255,), anchor='ls')
    draw.text((pad_x + des, baseline), 'OS', font=face, fill=ACCENT + (255,), anchor='ls')
    # The bracket: top-left and bottom-right corners, as on the installer's welcome card.
    arm = 14
    for box in ((0, 0, arm, 1), (0, 0, 1, arm), (width - arm - 1, height - 2, width - 1, height - 1),
                (width - 2, height - arm - 1, width - 1, height - 1)):
        draw.rectangle(box, fill=ACCENT + (255,))
    x = width + 18
    draw.rectangle((x, 12, x, height - 13), fill=LINE + (255,))
    draw.text((x + 16, 27), 'DEs-UI DESKTOP', font=small, fill=SECONDARY + (255,), anchor='ls')
    draw.text((x + 16, 45), 'LINUX / UBUNTU BASE', font=small, fill=FAINT + (255,), anchor='ls')
    save(image, out / 'wordmark.png')


def icon_canvas():
    from PIL import Image, ImageDraw
    scale = 8
    image = Image.new('RGBA', (ICON * scale, ICON * scale), (0, 0, 0, 0))
    return image, ImageDraw.Draw(image), scale


def build_icons(out):
    """Line icons on a 24px grid, 2px strokes: text ink with one accent stroke."""
    from PIL import Image
    icons = out / 'icons'
    icons.mkdir()
    ink, accent, dim = TEXT + (255,), ACCENT + (255,), SECONDARY + (255,)

    def draw_icon(name, painter):
        image, draw, s = icon_canvas()

        def line(points, colour=ink, width=2):
            draw.line([(x * s, y * s) for x, y in points], fill=colour, width=width * s, joint='curve')

        def rect(x0, y0, x1, y1, colour=ink, width=2):
            draw.rectangle((x0 * s, y0 * s, x1 * s - 1, y1 * s - 1), outline=colour, width=width * s)

        def block(x0, y0, x1, y1, colour=ink):
            draw.rectangle((x0 * s, y0 * s, x1 * s - 1, y1 * s - 1), fill=colour)

        def ring(x0, y0, x1, y1, colour=ink, width=2, start=0, end=360):
            draw.arc((x0 * s, y0 * s, x1 * s - 1, y1 * s - 1), start, end, fill=colour, width=width * s)

        painter(line, rect, block, ring)
        image = image.resize((ICON, ICON), Image.LANCZOS)
        save(image, icons / f'{name}.png')
        for alias in ICON_ALIASES.get(name, []):
            shutil.copyfile(icons / f'{name}.png', icons / f'{alias}.png')

    def desos(line, rect, block, ring):          # the bracket and a filled core
        line([(3, 10), (3, 3), (10, 3)], accent)
        line([(21, 14), (21, 21), (14, 21)], accent)
        block(8, 8, 16, 16)

    def install(line, rect, block, ring):        # arrow into a tray
        line([(4, 15), (4, 20), (20, 20), (20, 15)])
        line([(12, 3), (12, 14)], accent)
        line([(7, 10), (12, 15), (17, 10)], accent)

    def compat(line, rect, block, ring):         # a second, stacked kernel
        rect(3, 9, 15, 21, dim)
        rect(9, 3, 21, 15)
        block(13, 7, 17, 11, accent)

    def debug(line, rect, block, ring):          # prompt and cursor
        rect(2, 4, 22, 20)
        line([(6, 9), (9, 12), (6, 15)], accent)
        line([(12, 15), (17, 15)])

    def recovery(line, rect, block, ring):       # lifeline cross
        rect(3, 3, 21, 21, dim)
        line([(12, 7), (12, 17)], accent)
        line([(7, 12), (17, 12)], accent)

    def disk(line, rect, block, ring):           # drive with an activity light
        rect(3, 6, 21, 18)
        line([(3, 13), (21, 13)], dim, 1)
        block(16, 15, 18, 16, accent)

    def firmware(line, rect, block, ring):       # a chip
        rect(6, 6, 18, 18)
        block(10, 10, 14, 14, accent)
        for at in (9, 15):
            line([(at, 2), (at, 6)], dim)
            line([(at, 18), (at, 22)], dim)
            line([(2, at), (6, at)], dim)
            line([(18, at), (22, at)], dim)

    def snapshot(line, rect, block, ring):       # a clock face: a point in time
        ring(3, 3, 21, 21)
        line([(12, 7), (12, 12), (16, 14)], accent)

    def snapshots(line, rect, block, ring):      # stacked points in time
        line([(4, 8), (4, 4), (20, 4), (20, 8)], dim)
        line([(4, 13), (4, 10), (20, 10), (20, 13)], dim)
        rect(3, 15, 21, 21)
        block(6, 17, 9, 19, accent)

    def known_good(line, rect, block, ring):     # return arrow and a tick
        ring(4, 4, 20, 20, ink, 2, 30, 300)
        line([(15, 2), (19, 6), (14, 8)])
        line([(8, 12), (11, 15), (16, 9)], accent)

    def submenu(line, rect, block, ring):        # list with a way in
        line([(3, 6), (13, 6)])
        line([(3, 12), (13, 12)], dim)
        line([(3, 18), (13, 18)], dim)
        line([(16, 8), (20, 12), (16, 16)], accent)

    def memtest(line, rect, block, ring):        # a memory module
        rect(2, 7, 22, 17)
        for at in (6, 10, 14, 18):
            line([(at, 17), (at, 20)], dim)
        block(6, 10, 9, 14, accent)
        block(11, 10, 14, 14)
        block(16, 10, 19, 14)

    def power(line, rect, block, ring):
        ring(4, 5, 20, 21, ink, 2, 300, 240)
        line([(12, 3), (12, 12)], accent)

    for name, painter in [('desos', desos), ('install', install), ('compat', compat), ('debug', debug),
                          ('recovery', recovery), ('disk', disk), ('firmware', firmware),
                          ('snapshot', snapshot), ('snapshots', snapshots), ('known-good', known_good),
                          ('submenu', submenu), ('memtest', memtest), ('power', power)]:
        draw_icon(name, painter)


def build(out):
    out.mkdir(parents=True, exist_ok=True)
    (out / 'theme.txt').write_text(theme_text())
    build_fonts(out)
    build_boxes(out)
    build_wordmark(out)
    build_icons(out)
    for licence in ('ChakraPetch-OFL.txt', 'JetBrainsMono-OFL.txt'):
        shutil.copyfile(FONTS / licence, out / licence)


def tree(path):
    return sorted(item.relative_to(path).as_posix() for item in path.rglob('*') if item.is_file())


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='compare a fresh build with the committed theme')
    parser.add_argument('--output', type=pathlib.Path, help='write somewhere other than the committed theme')
    args = parser.parse_args()
    if args.check:
        with tempfile.TemporaryDirectory() as temporary:
            fresh = pathlib.Path(temporary) / 'desos'
            build(fresh)
            names = tree(fresh)
            if names != tree(THEME):
                raise SystemExit('theme file list differs from generator output')
            _, mismatch, errors = filecmp.cmpfiles(fresh, THEME, names, shallow=False)
            if mismatch or errors:
                raise SystemExit('theme differs from generator output: ' + ', '.join(mismatch + errors))
        print('theme matches generator output')
        return
    out = args.output or THEME
    if out.exists():
        if not (out / 'theme.txt').is_file():
            raise SystemExit(f'refusing to replace a directory that is not a theme: {out}')
        shutil.rmtree(out)
    build(out)
    print(f'{len(tree(out))} files in {out}')


if __name__ == '__main__':
    sys.exit(main())
